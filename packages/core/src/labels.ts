export interface PartialLabels {
  facts?: Partial<LabelSet["facts"]>;
  generatedBy?: string;
  additionKinds?: Partial<LabelSet["additionKinds"]>;
  filterMaterials?: Partial<LabelSet["filterMaterials"]>;
  brew?: Partial<LabelSet["brew"]>;
  /** Open on purpose, unlike the defaults: a consumer must be able to localize a
   *  token this build does not know, exactly as it must not reject a document for
   *  carrying one. */
  methods?: Record<string, string>;
  processes?: Record<string, string>;
  stepKinds?: Record<string, string>;
  roastLevels?: Record<string, string>;
  grindSizes?: Record<string, string>;
  producerRoles?: Record<string, string>;
  decodeErrors?: Partial<LabelSet["decodeErrors"]>;
  beanFallback?: string;
  badge?: string;
}

// Prototype-less for the reason `defaultLabels` is.
const vocabulary = <T extends Record<string, string>>(
  base: T,
  overrides?: Record<string, string>,
): T => Object.assign(Object.create(null) as T, base, overrides);

// Deep-merge over the English defaults: `facts` key-by-key, a vocabulary by
// token, so an unnamed default survives either way.
export function mergeLabels(overrides?: PartialLabels): LabelSet {
  return {
    facts: { ...defaultLabels.facts, ...overrides?.facts },
    generatedBy: overrides?.generatedBy ?? defaultLabels.generatedBy,
    additionKinds: {
      ...defaultLabels.additionKinds,
      ...overrides?.additionKinds,
    },
    filterMaterials: {
      ...defaultLabels.filterMaterials,
      ...overrides?.filterMaterials,
    },
    brew: { ...defaultLabels.brew, ...overrides?.brew },
    methods: vocabulary(defaultLabels.methods, overrides?.methods),
    processes: vocabulary(defaultLabels.processes, overrides?.processes),
    stepKinds: vocabulary(defaultLabels.stepKinds, overrides?.stepKinds),
    roastLevels: vocabulary(defaultLabels.roastLevels, overrides?.roastLevels),
    grindSizes: vocabulary(defaultLabels.grindSizes, overrides?.grindSizes),
    producerRoles: vocabulary(
      defaultLabels.producerRoles,
      overrides?.producerRoles,
    ),
    decodeErrors: { ...defaultLabels.decodeErrors, ...overrides?.decodeErrors },
    beanFallback: overrides?.beanFallback ?? defaultLabels.beanFallback,
    badge: overrides?.badge ?? defaultLabels.badge,
  };
}
