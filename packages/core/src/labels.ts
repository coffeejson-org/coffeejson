export interface LabelSet {
  facts: {
    dose: string;
    coffee: string;
    water: string;
    ratio: string;
    waterTemp: string;
    grind: string;
    pressure: string;
    preinfusion: string;
    basket: string;
    filter: string;
    shotTime: string;
    finish: string;
    roaster: string;
    origin: string;
    process: string;
    varietals: string;
    roast: string;
    roasterNotes: string;
    additions: string;
    /** Caption for the Agtron roast-color reading, e.g. "Agtron 62". */
    agtron: string;
    /** Caption for an origin item's harvest period, e.g. "Harvest Oct–Dec 2024". */
    harvest: string;
  };
  /** Prefix for the document's `generator` — "Generated by ExampleBrewApp 2.3.0".
   *  Document-level, so it sits outside `facts` (which labels recipe rows). */
  generatedBy: string;
  additionKinds: { ice: string; other: string };
  /** Filter materials — a closed vocabulary; an unrecognized value reads as `other`. */
  filterMaterials: Record<FilterMaterial, string>;
  /**
   * The brew-timer surface, not card rows. `next` and `reset` are full phrases
   * ("Start over") because `<BrewControls>` uses them as accessible names of
   * icon-only buttons; `step`, `pour`, `total` and `pourTo` are prefixes the
   * component completes ("<pourTo> 250 g").
   */
  brew: {
    pause: string;
    resume: string;
    next: string;
    reset: string;
    nextPourIn: string;
    finishIn: string;
    now: string;
    complete: string;
    getReady: string;
    step: string;
    pour: string;
    total: string;
    pourTo: string;
    pourCounter: string;
    done: string;
    /** Unit suffix for a duration stated in seconds, e.g. "5 s". */
    seconds: string;
  };
  /**
   * Every closed vocabulary a renderer prints, keyed by its union so a token the
   * format grows is a compile error here rather than a slug on screen. A
   * component never spells a token: it reads one of these. The spec's two
   * fallbacks fall out of the tables themselves — see `vocabularyLabel`.
   */
  methods: Record<BrewMethod, string>;
  processes: Record<Process, string>;
  stepKinds: Record<StepKind, string>;
  roastLevels: Record<RoastLevel, string>;
  grindSizes: Record<GrindSize, string>;
  /** The recommended producer roles. The registry is open, so the lookup falls
   *  back to the token — see `roleLabel`, not `vocabularyLabel`. */
  producerRoles: Record<RecommendedProducerRole, string>;
  /**
   * One sentence per decode reason, keyed by the codec's own vocabulary so a
   * reason the format grows is a compile error rather than a blank cell. A
   * consumer's own post-decode failures are its own words, not these.
   */
  decodeErrors: Record<DecodeError["kind"], string>;
  beanFallback: string;
  badge: string;
}

